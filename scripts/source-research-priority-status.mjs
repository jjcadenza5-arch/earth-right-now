import {recencyState} from "../src/source-recency.js";
import fs from "node:fs";
const file=new URL("../data/source-research-priorities.json",import.meta.url);
const data=JSON.parse(fs.readFileSync(file,"utf8"));
const sources=JSON.parse(fs.readFileSync(new URL("../data/sources.json",import.meta.url),"utf8"));
const now=new Date();
const w=data.scoringWeights||{};
const total=Object.values(w).reduce((a,b)=>a+Number(b||0),0);
const fail=[];
if(Math.abs(total-1)>1e-9) fail.push(`weights must total 1, got ${total}`);
if(Number(w.practicalCommercialFit)>0.05) fail.push("commercial fit exceeds 5% cap");
if(data.invariants?.commercialMayOverrideTruth!==false) fail.push("commercial truth override must remain false");
if(data.invariants?.commercialMayOverrideQuality!==false) fail.push("commercial quality override must remain false");
if(data.invariants?.commercialMayAffectWatchEarthRanking!==false) fail.push("commercial Watch Earth ranking effect must remain false");
if(data.invariants?.placeCategoriesAreIllustrativeNotRestrictive!==true) fail.push("place categories must remain illustrative, not restrictive");
if(data.invariants?.providerConcentrationMayRaiseResearchPriority!==true) fail.push("provider concentration research-priority modifier missing");
if(data.invariants?.providerConcentrationMayAffectWatchEarthRanking!==false) fail.push("provider concentration may affect Watch Earth ranking");
if(data.invariants?.providerConcentrationMayOverrideTruth!==false) fail.push("provider concentration may override truth");
if(data.invariants?.providerConcentrationMayOverrideQuality!==false) fail.push("provider concentration may override quality");
const activeCouchTourist=sources.filter(x=>/couchtourist/i.test(String(x.provider||"")+" "+String(x.sourceUrl||"")+" "+String(x.officialUrl||""))).length;
const declaredCouchTourist=Number(data.operationalResearchModifiers?.providerDiversification?.currentActiveCouchTouristSources);
if(!Number.isFinite(declaredCouchTourist)||declaredCouchTourist!==activeCouchTourist)fail.push("declared active CouchTourist dependency count does not match catalog");
if(!Array.isArray(data.placeUniverse)||data.placeUniverse.length<8) fail.push("place universe is unexpectedly narrow");
const stale=data.currentStaleDebt;
const staleItems=Array.isArray(stale?.items)?stale.items:[];
if(!stale||!staleItems.length||Number(stale.total)!==staleItems.length)fail.push("current stale-debt classification missing or count mismatch");
const allowedClasses=new Set(["PLAYBACK_EVIDENCE_DEBT","SEASONAL_OFF_SEASON","EDITORIAL_CURRENTNESS_DEBT","STALE_COMPANION_IMAGE","PROVIDER_OFFLINE"]);
const allowedPriorities=/^(HIGH|LOW|LOW_UNTIL_SEASON_OR_MATERIAL_CHANGE|ROUTINE)$/;
const sourceById=new Map(sources.map(x=>[String(x.id),x]));
const declaredProductionPlaces=Number(data.operationalResearchModifiers?.productionReality?.currentHealthyDistinctPlaces);
const actualHealthyPlaces=new Set(sources.filter(x=>x.health==="HEALTHY").map(x=>x.placeId||x.id)).size;
if(Number.isFinite(declaredProductionPlaces)&&declaredProductionPlaces<actualHealthyPlaces)fail.push("production-reality baseline trails core healthy-place reality");
for(const item of staleItems){
  if(!allowedClasses.has(String(item.class||"")))fail.push("stale debt class invalid: "+String(item.class||""));
  if(!allowedPriorities.test(String(item.priority||"")))fail.push("stale debt priority label invalid: "+String(item.priority||""));
  const source=sourceById.get(String(item.id||""));
  if(!source){fail.push("declared stale debt source missing from catalog: "+String(item.id||""));continue}
  const state=recencyState(source,{now});
  if(state==="CURRENT_CHECK")fail.push("declared stale debt entry is current and should be reconciled: "+item.id);
  if(state==="UNKNOWN")fail.push("declared stale debt entry has unknown recency: "+item.id);
}
const routineRecencyQueue=sources.filter(x=>recencyState(x,{now})==="STALE_CHECK"&&!staleItems.some(item=>item.id===x.id)).map(x=>x.id).sort();
console.log(JSON.stringify({ok:fail.length===0,totalWeight:total,commercialWeight:w.practicalCommercialFit,placeUniverseCount:data.placeUniverse?.length||0,activeCouchTourist,persistentStaleDebt:staleItems.map(x=>x.id),routineRecencyQueue,fail},null,2));
if(fail.length) process.exit(1);
