import fs from "node:fs";
import {execFileSync} from "node:child_process";
const read=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const run=p=>JSON.parse(execFileSync(process.execPath,[p],{encoding:"utf8"}));
const phase=run("scripts/project-phase-status.mjs");
const status=run("scripts/phase8-operating-status.mjs");
const plan=read("data/phase8-workplan.json");
const policy=read("data/phase8-current-collection-policy.json");
const html=fs.readFileSync("index.html","utf8");
const builder=fs.readFileSync("scripts/build-destination-pages.mjs","utf8");
const i18n=fs.readFileSync("src/home-i18n.js","utf8");
const blockers=[];
if(Number(phase.phaseNumber)<8)blockers.push("CANONICAL_PHASE_BEFORE_8");
if(status.entryApproved!==true||status.separateFeatureGatesRemainOff!==true)blockers.push("PHASE8_OPERATING_BOUNDARY");
if(!html.includes('id="editorialCollections"'))blockers.push("HOMEPAGE_COLLECTIONS_MISSING");
for(const id of ["beaches-water","mountains-snow","cities-streets","wildlife-nature","calm-scenic"])if(!html.includes("./discover/"+id+"/"))blockers.push("HOMEPAGE_COLLECTION_LINK_"+id);
if(!builder.includes("EDITORIAL_COLLECTIONS")||!builder.includes("editorialCollectionRows"))blockers.push("SHARED_COLLECTION_ENGINE_NOT_WIRED");
if(!builder.includes("Share this collection"))blockers.push("COLLECTION_SHAREABILITY_MISSING");
for(const key of ["collectionsHeading","collectionWater","collectionMountains","collectionCities","collectionWildlife","collectionCalm"])if(!i18n.includes(key))blockers.push("MULTILINGUAL_COLLECTION_COPY_"+key);
if(policy?.decision!=="KEEP_EVERGREEN_COLLECTIONS_STATIC_AND_CURRENT_MOMENTS_IN_WATCH_EARTH")blockers.push("CURRENT_COLLECTION_POLICY_MISSING");
const unfinished=(plan.lanes||[]).filter(x=>x.id!=="phase8-exit-review"&&x.status!=="COMPLETE");
const report={schemaVersion:1,phase:8,label:"Phase 8 Exit Review",ready:blockers.length===0&&unfinished.length===0,blockers,unfinishedLanes:unfinished.map(x=>x.id),separateFeatureGatesRemainOff:status.separateFeatureGatesRemainOff,next:blockers.length||unfinished.length?"FINISH_PHASE8_LANES":"MARK_PHASE8_COMPLETE_AND_ASSESS_NEXT_PHASE",safety:{automaticPostingAllowed:false,analyticsActivationAllowed:false,socialAccountActionAllowed:false,payoutAccountActionAllowed:false,separateFeatureActivationAllowed:false}};
console.log(JSON.stringify(report,null,2));
if(blockers.length||unfinished.length)process.exitCode=1;
