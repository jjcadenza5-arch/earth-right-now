import fs from "node:fs";
const cfg=await import("../src/analytics-config.js");
console.assert(cfg.analyticsReady()===true,"approved first-party analytics should be configured");
console.assert(cfg.analyticsConfig.provider==="ERN_FIRST_PARTY");
console.assert(cfg.analyticsConfig.privacyMode==="AGGREGATE_ONLY");
const runtime=fs.readFileSync("src/analytics-runtime.js","utf8");
for(const s of ["navigator.doNotTrack","globalPrivacyControl","credentials:\"omit\"","ERN_TELEMETRY","ERN_EVENT","page_view","referrerHost","deviceClass"])console.assert(runtime.includes(s),s+" missing");
console.assert(!runtime.includes("document.cookie"),"analytics must not use cookies");
console.log("ERN first-party analytics runtime privacy guard passed");
const {default:assert}=await import('node:assert/strict');
const {default:vm}=await import('node:vm');
const {telemetryEnvelope}=await import('../src/telemetry-policy.js');
const listeners={},sent=[];
const sandbox={analyticsConfig:{endpoint:'https://example.com/analytics',privacyMode:'AGGREGATE_ONLY'},analyticsReady:()=>true,telemetryEnvelope,navigator:{doNotTrack:'0'},screen:{width:1200},document:{referrer:'',readyState:'loading',addEventListener:(n,f)=>listeners[n]=f},localStorage:{getItem:()=> 'test-local-id'},fetch:async(_url,options)=>{sent.push(JSON.parse(options.body));return{ok:true}},setTimeout,clearTimeout,queueMicrotask,location:{pathname:'/'}};
vm.runInNewContext(runtime.replace(/^import .*;\n/gm,'').replace('export const analyticsRuntime','const analyticsRuntime'),sandbox);
listeners.click({target:{closest:()=>({dataset:{id:'local-test-cafe'}})}});
assert.equal(sent.length,1);
assert.deepEqual(sent[0].event.data,{placeId:'local-test-cafe'});
assert.equal(sent[0].event.name,'place_opened');
assert.equal('query' in sent[0].event.data,false);
assert.equal('url' in sent[0].event.data,false);
console.log('Delegated information opens use the existing sanitized place-open envelope without click URLs or query joins');
